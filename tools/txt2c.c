/* txt2c — turn a text file into a C array, so a program can carry it.
 *
 *   txt2c NAME < file > header.h
 *
 * writes `static const char NAME[] = { ..., 0 };`. An array rather than a
 * string literal, because compilers need only accept literals of 4095
 * characters and the file is longer. Used at build time to put Cozy's dsge
 * package inside the macro simulations.
 *
 * Part of econ-sims. Copyright (C) 2026 Mico Mrkaic.
 * GPL-3.0-or-later; see LICENSE. */
#include <stdio.h>

int main(int argc, char **argv)
{
    if (argc != 2) { fprintf(stderr, "usage: txt2c NAME < file > header.h\n"); return 2; }
    printf("/* GENERATED by tools/txt2c at build time; do not edit. */\nstatic const char %s[] = {", argv[1]);
    int c, n = 0;
    while ((c = getchar()) != EOF) printf("%s%d,", n++ % 24 ? "" : "\n", (signed char)c);   /* UTF-8 bytes as chars */
    printf("\n0};\n");
    return 0;
}
